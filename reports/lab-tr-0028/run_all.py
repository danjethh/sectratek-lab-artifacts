"""Reproduce everything that can be reproduced without the private corpus.

    python run_all.py --out DIR [--seed N] [--archive-seed N] [--reps N]

Writes into DIR:
  table9_fixtures.md / .csv         Table 9 (11 fixture scenarios, 4 rules, exact boundary), mean of --reps runs
  boundary_error_statements.csv     the three boundary-error statements of Section 5.7
  fig1_timeline.svg                 Figure 1 (schematic)
  fig4_recall.svg                   Figure 4 (from the fixture results)
  invented_archives/                invented archives and their configuration file (config.json)
  pipeline/                         report.md, report.json, fig2_gap.svg, fig3_shares.svg from the invented
                                    archives: this shows that the readers and the analysis run; it is not a result.
Defaults: seed 2810 (fixtures), archive seed 28, 200 repetitions. The output has no timestamp and no path.
"""
import argparse
import os

import fixtures
import figures
import gen_archives
import run_corpus
import tables

BANNER = ("INVENTED ARCHIVES: this report shows that the pipeline runs end to end on archives generated by "
          "gen_archives.py. The numbers describe the invented archives, not any device and not the findings of the report.")


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True)
    ap.add_argument("--seed", type=int, default=fixtures.DEFAULT_SEED)
    ap.add_argument("--archive-seed", type=int, default=gen_archives.DEFAULT_SEED)
    ap.add_argument("--reps", type=int, default=fixtures.DEFAULT_REPS)
    args = ap.parse_args()
    out = args.out
    os.makedirs(out, exist_ok=True)

    # fixtures: Table 9, Section 5.7 statements, Figure 4
    results = fixtures.run(seed=args.seed, reps=args.reps)
    header, rows = tables.table9(results)
    write(os.path.join(out, "table9_fixtures.md"),
          "Table 9: recall of restored records / share of native records flagged, percent, mean of %d runs, "
          "exact boundary, seed %d.\n\n%s\n" % (args.reps, args.seed, tables.md_table(header, rows)))
    write(os.path.join(out, "table9_fixtures.csv"), tables.csv_text(header, rows))
    h2, r2 = tables.boundary_errors(results)
    write(os.path.join(out, "boundary_error_statements.csv"), tables.csv_text(h2, r2))
    write(os.path.join(out, "fig4_recall.svg"), figures.fig4_recall(results, list(fixtures.SCENARIOS), fixtures.NO_RESTORE))
    write(os.path.join(out, "fig1_timeline.svg"), figures.fig1_timeline())

    # invented archives through the readers and the analysis
    arch = os.path.join(out, "invented_archives")
    gen_archives.generate(arch, args.archive_seed)
    cfg = run_corpus.load_config(os.path.join(arch, "config.json"))
    android, bugs, ios = run_corpus.read_all(cfg)
    import analyse
    analysis = analyse.analyse(android, bugs, ios)
    run_corpus.write_outputs(os.path.join(out, "pipeline"), analysis, BANNER)
    print("done: %s" % os.path.basename(os.path.normpath(out)))


if __name__ == "__main__":
    main()
